import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { config } from './config';
import { addExpressionShots, readShotList } from './expression-shot-list';
import { applyShotTags, fillInShotTags, parseShotTags, shotTagsPrompt } from './expression-shot-tags';
import { generationLines, parseGeneration } from './expression-generation-record';
import { mergeModelAssessments } from './expression-assessment';
import { parseTags } from './expressions';
import { makeTree, removeTree } from './testing';

let root: string; let saved: { projects: string; expressions: string };
beforeEach(() => {
  root = makeTree({ 'Projects/Video/Longform/Packaging/': '', 'Expressions/': '' });
  saved = { projects: config.videoProjectsDir, expressions: config.expressionsDir };
  config.videoProjectsDir = path.join(root, 'Projects'); config.expressionsDir = path.join(root, 'Expressions');
});
afterEach(() => { config.videoProjectsDir = saved.projects; config.expressionsDir = saved.expressions; removeTree(root); });

const ASSURED = 'Composure > Confidence (looking straight at the camera, one eyebrow gently raised, mouth slightly parted, no squint)';

describe("filling in a look's tags from its description", () => {
  it('asks with the library vocabulary and keeps only real tag words, each in its own list', () => {
    const shots = addExpressionShots('Video/Longform', [{ expression: ASSURED, context: 'Top 1' }]);
    const prompt = shotTagsPrompt(shots);
    expect(prompt).toContain('RaisedBrow'); expect(prompt).toContain('LookAtCamera'); expect(prompt).toContain(shots[0].id);
    const id = shots[0].id;
    const found = parseShotTags(`Here: {"looks": [{"id": "${id}", "framing": ["closeup", "Smile"], "pose": ["LookAtCamera"], "morphology": ["RaisedBrow", "Asymmetric", "MouthOpen", "Sparkle"], "ruledOut": ["Squint", "MouthOpen", "EyesWide"]}, {"id": "unknown", "pose": ["LookUp"]}]}`, shots);
    // "Smile" is not a framing word and "Sparkle" is not a tag; a tag can't be both given and ruled out.
    expect(found.get(id)).toEqual({ framing: ['CloseUp'], pose: ['LookAtCamera'], morphology: ['RaisedBrow', 'Asymmetric', 'MouthOpen'], ruledOut: ['Squint', 'EyesWide'] });
    expect(found.has('unknown')).toBe(false);
    expect(() => parseShotTags('Sorry, no.', shots)).toThrow(/did not answer/);
  });

  it('only adds tags: a look keeps its own, never gains a tag it rules out, and never rules out one it has', () => {
    const [shot] = addExpressionShots('Video/Longform', [{ expression: ASSURED, context: 'Top 1' }]);
    shot.pose = ['HeadTilt']; shot.ruledOut = ['Smile'];
    const changed = applyShotTags([shot], new Map([[shot.id, { framing: [], pose: ['LookAtCamera'], morphology: ['Smile', 'RaisedBrow'], ruledOut: ['HeadTilt', 'Squint'] }]]));
    expect(changed).toBe(1);
    expect(shot).toMatchObject({ pose: ['HeadTilt', 'LookAtCamera'], morphology: ['RaisedBrow'], ruledOut: ['Smile', 'Squint'] });
    expect(applyShotTags([shot], new Map([[shot.id, { framing: [], pose: ['LookAtCamera'], morphology: [], ruledOut: [] }]]))).toBe(0);
  });

  it('Fill In Tags asks about every look and saves the tags', async () => {
    addExpressionShots('Video/Longform', [{ expression: ASSURED, context: 'Top 1' }, { expression: 'Positive > Joy (a big grin)', context: 'Idea 2' }]);
    let asked = 0;
    const result = await fillInShotTags(async prompt => {
      asked++;
      const looks = JSON.parse(prompt.split('\n\n').pop()!) as { id: string; look: string }[];
      return JSON.stringify({ looks: looks.map(l => ({ id: l.id, morphology: l.look.includes('grin') ? ['Grin'] : ['RaisedBrow'], ruledOut: l.look.includes('squint') ? ['Squint'] : [] })) });
    });
    expect(asked).toBe(1); expect(result.tagged).toBe(2);
    expect(readShotList().map(s => [s.morphology, s.ruledOut])).toEqual([[['RaisedBrow'], ['Squint']], [['Grin'], undefined]]);
  });
});

describe("an AI picture's record of what it was asked for", () => {
  const record = { by: 'gemini', look: 'Direct and Assured', description: 'Looking at the camera,\nno squint.', with: ['LookAtCamera', 'RaisedBrow', 'LookAtCamera'], without: ['Squint'] };

  it('is kept as "#" lines that read back the same', () => {
    const lines = generationLines(record);
    expect(lines).toBe('# Generated by: Gemini\n# Generated look: Direct and Assured\n# Generated description: Looking at the camera, no squint.\n# Generated with: LookAtCamera, RaisedBrow\n# Generated without: Squint\n');
    expect(parseGeneration(`Smile, N/A, UNCONFIRMED\n${lines}`)).toEqual({ by: 'Gemini', look: 'Direct and Assured', description: 'Looking at the camera, no squint.', with: ['LookAtCamera', 'RaisedBrow'], without: ['Squint'] });
    expect(parseGeneration('Smile, N/A, UNCONFIRMED\n')).toBeUndefined();
    expect(parseTags(lines)).toEqual([]);
  });

  it('stays apart from the AI assessment, which records its own scores and leaves the record alone', () => {
    const sidecar = `LookAtCamera, N/A, UNCONFIRMED\n==========\nSquint, N/A, DISCONFIRMED\n==========\nAIGenerated, N/A, CONFIRMED\n${generationLines(record)}`;
    const assessed = mergeModelAssessments(sidecar, { gemini: [{ tag: 'LookAtCamera', confidence: 88 }, { tag: 'Squint', confidence: 80 }] }, []);
    expect(assessed).toContain('LookAtCamera, 88%, UNCONFIRMED, gemini=88%');
    expect(assessed).toContain('Squint, N/A, DISCONFIRMED, gemini=80%');
    expect(parseGeneration(assessed)).toEqual(parseGeneration(sidecar));
  });
});
